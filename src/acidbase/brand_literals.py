"""Find brand values pasted into source instead of coming from the cosmetics repo.

``cosmetics`` is the authority for design values, and repos commit the files it generates. A hex value or font name
typed by hand drifts without anyone noticing, so ``acidbase hooks`` lists them as warnings. Some files must embed
literals, so the scan covers source files only, skips anything stamped as generated, and honours a repo's
``[tool.acidbase.brand] exempt`` globs.
"""

from __future__ import annotations

import fnmatch
import re
import subprocess
import tomllib
from dataclasses import dataclass
from pathlib import Path, PurePosixPath

from acidbase.acidvuca_brand import COLOURS, FONT_FAMILY

_SOURCE_SUFFIXES = {".css", ".html", ".js", ".jsx", ".mako", ".py", ".scss", ".ts", ".tsx"}
_EXEMPT_FOLDERS = {"archive", "dist", "docs", "generated", "node_modules", "tests", "vendor"}
_GENERATED_STAMP = "Generated by cosmetics"
_STAMP_WINDOW = 400  # to find the stamp near the top without reading a whole file for it
_NEUTRALS = {"white", "black"}
_HEX_VALUES = "|".join(value.lstrip("#") for name, value in COLOURS.items() if name not in _NEUTRALS)
_LITERAL_PATTERN = re.compile(rf"(?i)#(?:{_HEX_VALUES})(?:[0-9a-f]{{2}})?\b|{re.escape(FONT_FAMILY)}")


@dataclass(frozen=True)
class BrandLiteral:
    """One pasted brand value."""

    path: str
    line: int
    value: str


def _exempt_globs(repo_root: Path) -> list[str]:
    """Reads a repo's own exemptions from pyproject.toml, returning none when it has no readable table."""
    try:
        data = tomllib.loads((repo_root / "pyproject.toml").read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, tomllib.TOMLDecodeError):
        return []
    return data.get("tool", {}).get("acidbase", {}).get("brand", {}).get("exempt", [])


def _tracked_files(repo_root: Path) -> list[str]:
    """Lists tracked files, returning none outside a Git checkout."""
    try:
        done = subprocess.run(
            ["git", "-C", str(repo_root), "ls-files"], capture_output=True, encoding="utf-8", errors="replace"
        )
    except OSError:
        return []
    return done.stdout.splitlines() if done.returncode == 0 else []


def _in_scope(relative: str, exempt: list[str]) -> bool:
    """Says whether a tracked file is source code that should come from the brand."""
    path = PurePosixPath(relative)
    if path.suffix not in _SOURCE_SUFFIXES or _EXEMPT_FOLDERS.intersection(path.parts[:-1]):
        return False
    return not any(fnmatch.fnmatch(relative, pattern) for pattern in exempt)


def find_brand_literals(repo_root: Path) -> list[BrandLiteral]:
    """Returns every brand value pasted into a repo's tracked source files."""
    exempt = _exempt_globs(repo_root)
    findings: list[BrandLiteral] = []
    for relative in _tracked_files(repo_root):
        if not _in_scope(relative, exempt):
            continue
        try:
            text = (repo_root / relative).read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        if _GENERATED_STAMP in text[:_STAMP_WINDOW]:
            continue
        for number, line in enumerate(text.splitlines(), start=1):
            findings.extend(BrandLiteral(relative, number, match[0]) for match in _LITERAL_PATTERN.finditer(line))
    return findings

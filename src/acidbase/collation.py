"""Abecedarian collation for the a6a ecosystem.

Mirrors the cross-language abecedary (``abc.md``, generated by ``make_abc.py``):

* Zone P first: ASCII 0..63 in codepoint order, then ``¿``, ``¡``, ``@``,
  ASCII 91..96 (``[\\]^_```), and ASCII 123..127 (``{|}~`` and DEL).
* Then the alphabet with case interleaved: ``A a <A-variants> B b ... Z z``.

Plain codepoint order (``sorted()``) differs in two visible ways: ``_`` and
``[\\]^``` sort *between* upper- and lowercase letters, and every capital
precedes every small letter (``Z`` < ``a``).

Non-ASCII letters are placed after their base letter (NFD decomposition,
combining marks stripped), tie-broken by codepoint; this approximates the
abecedary's hand-curated variant order. Anything else that is not in the
table sorts after ``z`` by codepoint.
"""

from __future__ import annotations

import string
import unicodedata
from collections.abc import Iterable

_ZONE_P = (
    [chr(cp) for cp in range(64)]
    + ["\u00bf", "\u00a1", "@"]
    + [chr(cp) for cp in range(91, 97)]
    + [chr(cp) for cp in range(123, 128)]
)
_LETTER_BASE = len(_ZONE_P)
# Per letter: slot 0 = capital, 1 = small, 2 = variants (tie-broken by codepoint).
_LETTER_STRIDE = 3
_RANK: dict[str, int] = {ch: i for i, ch in enumerate(_ZONE_P)}
for _i, (_upper, _lower) in enumerate(zip(string.ascii_uppercase, string.ascii_lowercase, strict=True)):
    _RANK[_upper] = _LETTER_BASE + _i * _LETTER_STRIDE
    _RANK[_lower] = _LETTER_BASE + _i * _LETTER_STRIDE + 1
_UNRANKED = _LETTER_BASE + 26 * _LETTER_STRIDE


def _char_key(ch: str) -> tuple[int, int]:
    """Returns the (rank, tie-break) collation key of one character."""
    rank = _RANK.get(ch)
    if rank is not None:
        return rank, 0
    base = unicodedata.normalize("NFD", ch)[:1]
    base_rank = _RANK.get(base.upper()) if base.isascii() and base.isalpha() else None
    if base_rank is not None:
        return base_rank + 2, ord(ch)  # to sit after the base letter's capital and small forms
    return _UNRANKED, ord(ch)


def abc_key(text: str) -> tuple[tuple[int, int], ...]:
    """Returns a sort key ordering strings by the ecosystem abecedary.

    Strings compare character by character; a proper prefix sorts first.
    """
    return tuple(_char_key(ch) for ch in text)


def abc_sorted(items: Iterable[str]) -> list[str]:
    """Returns *items* sorted abecedarianly (stable for equal keys)."""
    return sorted(items, key=abc_key)

def test_patch_repo_returns_giterror_when_git_status_fails(tmp_path, monkeypatch):
    """Returns GITERROR (not DIRTY) when `git status` exits non-zero.

    Regression test for the WSL UNC misdiagnosis: prior to the
    ``_check_clean`` refactor, every non-zero exit from ``git status``
    (e.g. the ``fatal: detected dubious ownership in repository at '...'``
    that hits when Windows-native git runs against a WSL share) was
    collapsed into ``DIRTY`` / ``uncommitted changes``. The new behavior
    is to surface the real stderr through a dedicated ``GITERROR`` status.
    """
    repo = _make_repo(tmp_path)
    fake = RecordingShell(
        {
            ("git", "--no-pager", "status", "--porcelain", "--untracked-files=no"): CommandResult(
                128,
                "",
                "fatal: detected dubious ownership in repository at '//wsl.localhost/Ubuntu/home/user/some-repo'\n",
            ),
        }
    )
    monkeypatch.setattr(patcher, "shell", _stub_module(fake))
    profile = Profile(repo="r", path=repo)
    result = patch_repo(profile, dep_name="GitPython", new_version="3.1.50", cve_id="CVE-1")
    assert result.status is PatchStatus.GITERROR
    assert "dubious ownership" in result.note
    # The 200-char stderr truncation means the full URL may be cut, but the
    # diagnostic keyword has to be present.


def test_patch_repo_returns_selfskip_when_targeting_own_project_on_windows(tmp_path, monkeypatch):
    """Returns SELFSKIP with a copy-pasteable command when acidbase is asked to patch itself on Windows.

    Regression test for the python-dotenv UVADDFAIL on acidbase: the running
    python.exe holds open handles on its own site-packages files (rich →
    pygments, python-dotenv, click, ...), so an inner `uv add` against the
    same venv fails on Windows with `error: failed to remove file '...'`.
    The new SELFSKIP status defers the bump and surfaces a manual command
    instead of misreporting it as UVADDFAIL.
    """
    repo = _make_repo(tmp_path)
    monkeypatch.setattr(patcher, "shell", _stub_module(RecordingShell({})))
    monkeypatch.setattr(patcher, "_is_self_patching", lambda p: True)
    monkeypatch.setattr(patcher.sys, "platform", "win32")
    profile = Profile(repo="acidbase", path=repo, branch="main")
    result = patch_repo(profile, dep_name="Pygments", new_version="2.20.0", cve_id="CVE-1")
    assert result.status is PatchStatus.SELFSKIP
    # The user-facing note contains a runnable command sequence.
    assert "uv add" in result.note
    assert "Pygments>=2.20.0" in result.note
    assert "git push" in result.note


def test_patch_repo_proceeds_normally_when_self_patching_on_posix(tmp_path, monkeypatch):
    """SELFSKIP only fires on Windows; POSIX unlink-while-open semantics let uv proceed."""
    repo = _make_repo(tmp_path, with_requirements=True)
    calls: list[tuple[str, ...]] = []
    state = {"status_calls": 0}

    def fake_run(args, *, cwd=None, capture=True, check=False, env=None):
        key = tuple(args)
        calls.append(key)
        if key == ("git", "--no-pager", "status", "--porcelain", "--untracked-files=no"):
            state["status_calls"] += 1
            if state["status_calls"] == 1:
                return CommandResult(0, "", "")
            return CommandResult(0, "M pyproject.toml\n", "")
        return CommandResult(0, "", "")

    monkeypatch.setattr(patcher, "shell", _stub_module(fake_run))
    monkeypatch.setattr(patcher, "_is_self_patching", lambda p: True)
    monkeypatch.setattr(patcher.sys, "platform", "linux")
    profile = Profile(repo="acidbase", path=repo, branch="main")
    result = patch_repo(profile, dep_name="Pygments", new_version="2.20.0", cve_id="CVE-1")
    # Reaches DONE without ever taking the SELFSKIP branch.
    assert result.status is PatchStatus.DONE
    assert ("uv", "add", "--no-sync", "Pygments>=2.20.0") in calls



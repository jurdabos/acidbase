"""
Tests for :mod:`acidbase.security.patcher`.

The shell layer is replaced with a recording fake so the test asserts on the
exact sequence of git/uv invocations used by the patch flow.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Optional

from acidbase.security import patcher
from acidbase.security.patcher import PatchResult, PatchStatus, patch_repo
from acidbase.security.profiles import Profile
from acidbase.security.shell import CommandResult

_UV_LOCK = 'version = 1\n\n[[package]]\nname = "{dep}"\nversion = "{ver}"\n'
_UV_EXPORT_HEADER = (
    "# This file was autogenerated by uv via the following command:\n"
    "#    uv export --no-hashes --no-dev -o producer/requirements.txt\n"
)
_ROOT_EXPORT_HEADER = (
    "# This file was autogenerated by uv via the following command:\n"
    "#    uv export --frozen --output-file=requirements.txt\n"
)


class RecordingShell:
    """Fake replacement for :func:`acidbase.security.shell.run` used in tests."""

    def __init__(self, responses: dict[tuple[str, ...], CommandResult]) -> None:
        self.responses = responses
        self.calls: list[tuple[str, ...]] = []

    def __call__(
        self,
        args,
        *,
        cwd: Optional[Path] = None,
        capture: bool = True,
        check: bool = False,
        env=None,
    ) -> CommandResult:
        key = tuple(args)
        self.calls.append(key)
        for pattern, result in self.responses.items():
            if all(seg in key for seg in pattern):
                return result
        return CommandResult(returncode=0, stdout="", stderr="")


def _make_repo(tmp_path: Path, *, with_requirements: bool = False) -> Path:
    """Creates a fake repo skeleton (uv.lock + optionally requirements.txt)."""
    repo = tmp_path / "repo"
    repo.mkdir()
    (repo / "uv.lock").write_text("# fake lock\n", encoding="utf-8")
    (repo / "pyproject.toml").write_text("[project]\nname='r'\nversion='0'\n", encoding="utf-8")
    if with_requirements:
        (repo / "requirements.txt").write_text("", encoding="utf-8")
    return repo



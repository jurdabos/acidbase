def test_output_tail_joins_strips_and_truncates():
    """_output_tail joins stdout+stderr, passes short text through, keeps long tails."""
    assert patcher._output_tail("short", "") == "short"
    assert patcher._output_tail("a\n", "b\n") == "a\nb"

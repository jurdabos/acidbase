def test_patch_repo_full_happy_path(tmp_path, monkeypatch):
    """Clean tree + uv.lock produces DONE with the expected commit invocation."""
    repo = _make_repo(tmp_path, with_requirements=True)
    state = {"status_calls": 0}
    calls: list[tuple[str, ...]] = []

    def fake_run(args, *, cwd=None, capture=True, check=False, env=None):
        key = tuple(args)
        calls.append(key)
        if key == ("git", "--no-pager", "status", "--porcelain", "--untracked-files=no"):
            state["status_calls"] += 1
            # First status call (pre-flight) is clean; second (post-bump) is dirty.
            if state["status_calls"] == 1:
                return CommandResult(0, "", "")
            return CommandResult(0, "M pyproject.toml\n", "")
        return CommandResult(0, "", "")

    monkeypatch.setattr(patcher, "shell", _stub_module(fake_run))
    profile = Profile(repo="r", path=repo, branch="main")
    result = patch_repo(profile, dep_name="GitPython", new_version="3.1.50", cve_id="CVE-1")
    assert result.status is PatchStatus.DONE
    assert result.note == "bumped to >=3.1.50"
    # The bump invocation must use the >=NEW form expected by the runbook,
    # and --no-sync so the target repo's venv is never touched.
    assert ("uv", "add", "--no-sync", "GitPython>=3.1.50") in calls
    # Commit message follows the runbook template verbatim.
    assert any(
        c[:3] == ("git", "commit", "-m") and "security: update GitPython to 3.1.50 to fix CVE-1" in c for c in calls
    )
    # --sync-env is opt-in: no environment sync happens by default.
    assert not any(c[:2] == ("uv", "sync") for c in calls)


def _stub_module(fake_run):
    """Returns a tiny stand-in module exposing only the symbols patcher needs."""

    class Stub:
        run = fake_run
        # Defaulting to "not a WSL mount"; sync-gate tests override per case.
        wsl_routing = staticmethod(lambda cwd: None)
        CommandResult = CommandResult  # noqa: N815 (mirroring real module)

    return Stub


def _make_npm_repo(
    tmp_path: Path,
    *,
    lockfile_contents: dict,
    package_json_contents: Optional[dict] = None,
    subdir: str = ".",
    extra_files: tuple[str, ...] = (),
) -> Path:
    """Creates a fake npm repo skeleton with a package-lock.json (and optional siblings)."""
    repo = tmp_path / "repo"
    repo.mkdir()
    target = repo if subdir == "." else repo / subdir
    target.mkdir(parents=True, exist_ok=True)
    (target / "package-lock.json").write_text(json.dumps(lockfile_contents), encoding="utf-8")
    if package_json_contents is not None:
        (target / "package.json").write_text(json.dumps(package_json_contents), encoding="utf-8")
    for filename in extra_files:
        (target / filename).write_text("", encoding="utf-8")
    return repo



def test_self_skip_command_includes_requirements_export_when_file_exists(tmp_path):
    """The self-skip command suggests `uv export` only for a uv-export-artifact root file."""
    # _make_repo() expects its parent to exist already, so create the three
    # sibling parent dirs first before delegating.
    (tmp_path / "with").mkdir()
    (tmp_path / "without").mkdir()
    (tmp_path / "curated").mkdir()
    repo_with = _make_repo(tmp_path / "with", with_requirements=True)
    (repo_with / "requirements.txt").write_text(_ROOT_EXPORT_HEADER + "pytest==9.0.2\n", encoding="utf-8")
    cmd_with = patcher._self_skip_command(repo_with, "pytest", "9.0.3", "CVE-X")
    assert "uv export --frozen --output-file=requirements.txt" in cmd_with
    assert "requirements.txt" in cmd_with

    repo_without = _make_repo(tmp_path / "without")
    cmd_without = patcher._self_skip_command(repo_without, "pytest", "9.0.3", "CVE-X")
    assert "uv export" not in cmd_without
    assert "requirements.txt" not in cmd_without

    # A curated root file (no uv-export header) must not be suggested for export either.
    repo_curated = _make_repo(tmp_path / "curated", with_requirements=True)
    (repo_curated / "requirements.txt").write_text(
        "# synced by scripts/sync_requirements.py\npytest\n", encoding="utf-8"
    )
    cmd_curated = patcher._self_skip_command(repo_curated, "pytest", "9.0.3", "CVE-X")
    assert "uv export" not in cmd_curated
    assert "git add pyproject.toml uv.lock" in cmd_curated


def test_check_clean_distinguishes_clean_dirty_and_errored(tmp_path, monkeypatch):
    """_check_clean returns the documented 3-state tuple for each outcome."""
    repo = _make_repo(tmp_path)
    # Clean: rc=0, empty stdout
    fake_clean = RecordingShell({("git", "--no-pager", "status"): CommandResult(0, "", "")})
    monkeypatch.setattr(patcher, "shell", _stub_module(fake_clean))
    assert patcher._check_clean(repo) == (True, None)

    # Dirty: rc=0, non-empty stdout
    fake_dirty = RecordingShell({("git", "--no-pager", "status"): CommandResult(0, " M pyproject.toml\n", "")})
    monkeypatch.setattr(patcher, "shell", _stub_module(fake_dirty))
    assert patcher._check_clean(repo) == (False, None)

    # Errored: rc != 0 — error message is surfaced (truncated to 200 chars)
    fake_err = RecordingShell({("git", "--no-pager", "status"): CommandResult(128, "", "fatal: dubious ownership\n")})
    monkeypatch.setattr(patcher, "shell", _stub_module(fake_err))
    clean, err = patcher._check_clean(repo)
    assert clean is False
    assert err is not None
    assert "dubious ownership" in err



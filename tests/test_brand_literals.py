"""Tests the warning about brand values pasted into source."""

from __future__ import annotations

import subprocess
from pathlib import Path

import pytest
from click.testing import CliRunner

from acidbase.acidvuca_brand import COLOURS, FONT_FAMILY
from acidbase.brand_literals import find_brand_literals
from acidbase.hooks import hooks_command

PRIMARY = COLOURS["caribbean_current"]


def _repo(root: Path, files: dict[str, str]) -> Path:
    """Creates a Git repo with the given files tracked."""
    for relative, content in files.items():
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    subprocess.run(["git", "init", "-q", str(root)], check=True)
    subprocess.run(["git", "-C", str(root), "add", "-A"], check=True)
    return root


def test_finds_a_pasted_hex_value_with_its_location(tmp_path: Path) -> None:
    repo = _repo(tmp_path, {"src/app.py": f'BLUE = "ok"\nTEAL = "{PRIMARY}"\n'})
    findings = find_brand_literals(repo)
    assert [(f.path, f.line, f.value) for f in findings] == [("src/app.py", 2, PRIMARY)]


def test_finds_any_case_and_an_alpha_suffix(tmp_path: Path) -> None:
    repo = _repo(tmp_path, {"a.css": f"a {{ color: {PRIMARY.upper()}; background: {PRIMARY}33; }}\n"})
    assert len(find_brand_literals(repo)) == 2


def test_finds_the_font_name(tmp_path: Path) -> None:
    repo = _repo(tmp_path, {"a.css": f"body {{ font-family: '{FONT_FAMILY}'; }}\n"})
    assert [f.value for f in find_brand_literals(repo)] == [FONT_FAMILY]


def test_ignores_a_longer_hex_that_only_starts_like_a_brand_value(tmp_path: Path) -> None:
    repo = _repo(tmp_path, {"a.py": f'SHA = "{PRIMARY}0123456789"\n'})
    assert find_brand_literals(repo) == []


def test_ignores_white_and_black(tmp_path: Path) -> None:
    repo = _repo(tmp_path, {"a.css": "a { color: #ffffff; background: #000000; }\n"})
    assert find_brand_literals(repo) == []


def test_skips_files_stamped_as_generated(tmp_path: Path) -> None:
    content = f'"""\nGenerated by cosmetics from token/ (abc).\n"""\nTEAL = "{PRIMARY}"\n'
    repo = _repo(tmp_path, {"acidvuca_brand.py": content})
    assert find_brand_literals(repo) == []


@pytest.mark.parametrize(
    "path",
    ["tests/test_app.py", "docs/page.html", "vendor/lib.js", "archive/old.css", "generated/css/a.css", "logo.svg"],
)
def test_skips_tests_docs_and_files_that_must_embed_values(tmp_path: Path, path: str) -> None:
    repo = _repo(tmp_path, {path: f'TEAL = "{PRIMARY}"\n'})
    assert find_brand_literals(repo) == []


def test_honours_a_repos_own_exemptions(tmp_path: Path) -> None:
    files = {
        "pyproject.toml": '[tool.acidbase.brand]\nexempt = ["static/css/*"]\n',
        "static/css/styles.css": f"a {{ color: {PRIMARY}; }}\n",
        "static/js/app.js": f'const teal = "{PRIMARY}";\n',
    }
    assert [f.path for f in find_brand_literals(_repo(tmp_path, files))] == ["static/js/app.js"]


def test_skips_untracked_files(tmp_path: Path) -> None:
    repo = _repo(tmp_path, {"a.py": "x = 1\n"})
    (repo / "scratch.py").write_text(f'TEAL = "{PRIMARY}"\n', encoding="utf-8")
    assert find_brand_literals(repo) == []


def test_returns_nothing_outside_a_git_checkout(tmp_path: Path) -> None:
    (tmp_path / "a.py").write_text(f'TEAL = "{PRIMARY}"\n', encoding="utf-8")
    assert find_brand_literals(tmp_path) == []


def test_hooks_warns_without_failing_and_lists_examples(tmp_path: Path) -> None:
    lines = "".join(f'V{i} = "{PRIMARY}"\n' for i in range(7))
    repo = _repo(tmp_path, {"a.py": lines})
    result = CliRunner().invoke(hooks_command, [str(repo)])
    assert result.exit_code == 0
    assert "7 brand value(s) pasted by hand" in result.output
    assert "a.py:1" in result.output
    assert "...and 2 more" in result.output


def test_hooks_stays_quiet_about_a_clean_repo(tmp_path: Path) -> None:
    repo = _repo(tmp_path, {"a.py": "x = 1\n"})
    assert "brand value" not in CliRunner().invoke(hooks_command, [str(repo)]).output
